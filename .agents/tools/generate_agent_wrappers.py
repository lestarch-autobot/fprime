#!/usr/bin/env python3
"""Generate per-tool agent files from the `agent-*` skills.

Each agent's instructions live once, in `.agents/skills/agent-<name>/SKILL.md`.
The `metadata` block of that file carries what a skill cannot express (display
name, tool limits, who may start it). This script writes one thin agent file
per tool from it:

    .github/agents/<name>.agent.md   GitHub Copilot
    .claude/agents/<name>.md         Claude Code

Run with no arguments to rewrite the files, or with `--check` to fail when
they are missing, stale, or orphaned. Standard library only.
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKILLS = ROOT / ".agents" / "skills"
PREFIX = "agent-"
# Skills that carry the prefix without being agents.
PLAIN_SKILLS = {"agent-skill-authoring"}
MARKER = "<!-- Generated by .agents/tools/generate_agent_wrappers.py"
TOOL_CLASSES = ("read", "search", "edit", "execute")
CLAUDE_TOOLS = {
    "read": ["Read"],
    "search": ["Grep", "Glob"],
    "edit": ["Edit", "Write"],
    "execute": ["Bash"],
}
METADATA_KEYS = {
    "agent-name",
    "agent-tools",
    "agent-user-invocable",
    "agent-model-invocable",
}


class SpecError(Exception):
    """An agent skill's frontmatter is not in the form this script reads."""


def parse_value(raw, where):
    """Read one double-quoted scalar; the JSON string form is valid YAML."""
    try:
        value = json.loads(raw)
    except json.JSONDecodeError as error:
        raise SpecError(f"{where}: value must be a double-quoted string") from error
    if not isinstance(value, str):
        raise SpecError(f"{where}: value must be a double-quoted string")
    return value


def read_agent(skill_dir):
    """Return the agent described by one `agent-*` skill."""
    skill_file = skill_dir / "SKILL.md"
    if not skill_file.is_file():
        raise SpecError(f"{skill_file}: missing")
    lines = skill_file.read_text(encoding="utf-8").split("\n")
    if lines[0] != "---" or "---" not in lines[1:]:
        raise SpecError(f"{skill_file}: missing frontmatter")
    front = [line.rstrip() for line in lines[1 : lines.index("---", 1)]]
    if "metadata:" not in front:
        raise SpecError(
            f"{skill_file}: an `agent-*` skill needs a `metadata` block; a "
            "plain skill with that prefix must be listed in PLAIN_SKILLS"
        )
    top, meta, in_meta = {}, {}, False
    for line in front:
        match = re.fullmatch(r"(  )?([a-z-]+):(?: (.+))?", line)
        if not match:
            raise SpecError(f"{skill_file}: unsupported frontmatter line: {line!r}")
        indented, key, raw = match.groups()
        if not indented:
            in_meta = key == "metadata" and raw is None
        if in_meta and not indented:
            continue
        if indented and in_meta:
            meta[key] = parse_value(raw or "", f"{skill_file}: {key}")
        elif not indented and key == "name" and raw:
            # Unquoted: a skill name is lowercase letters, digits and hyphens.
            top[key] = raw
        elif not indented and raw:
            top[key] = parse_value(raw, f"{skill_file}: {key}")
        else:
            raise SpecError(f"{skill_file}: unsupported frontmatter line: {line!r}")
    if top.get("name") != skill_dir.name:
        raise SpecError(f"{skill_file}: `name` must equal the directory name")
    if not top.get("description"):
        raise SpecError(f"{skill_file}: missing `description`")
    if set(meta) != METADATA_KEYS:
        raise SpecError(
            f"{skill_file}: metadata keys must be exactly {sorted(METADATA_KEYS)}"
        )
    tools = meta["agent-tools"].split()
    if not tools or any(tool not in TOOL_CLASSES for tool in tools):
        raise SpecError(f"{skill_file}: agent-tools must be drawn from {TOOL_CLASSES}")
    flags = {}
    for key in ("agent-user-invocable", "agent-model-invocable"):
        if meta[key] not in ("true", "false"):
            raise SpecError(f'{skill_file}: {key} must be "true" or "false"')
        flags[key] = meta[key] == "true"
    return {
        "skill": skill_dir.name,
        "short": skill_dir.name[len(PREFIX) :],
        "title": meta["agent-name"],
        "description": top["description"],
        "tools": tools,
        "user_invocable": flags["agent-user-invocable"],
        "model_invocable": flags["agent-model-invocable"],
    }


def quote(text):
    return json.dumps(text, ensure_ascii=False)


def body(agent):
    path = f".agents/skills/{agent['skill']}/SKILL.md"
    return (
        f"{MARKER} from\n"
        f"     {path}. Do not edit; edit that file and regenerate. -->\n"
        f"You are the {agent['title']}. Your complete instructions are the\n"
        f"`{agent['skill']}` skill. Before doing anything else, read\n"
        f"`{path}` in full, unless its content is\n"
        f"already loaded in this session, and then follow it exactly.\n"
    )


def copilot_file(agent):
    return (
        "---\n"
        f"description: {quote(agent['description'])}\n"
        f"name: {quote(agent['title'])}\n"
        f"tools: [{', '.join(agent['tools'])}]\n"
        f"user-invocable: {str(agent['user_invocable']).lower()}\n"
        f"disable-model-invocation: {str(not agent['model_invocable']).lower()}\n"
        "---\n" + body(agent)
    )


def claude_file(agent):
    tools = [name for tool in agent["tools"] for name in CLAUDE_TOOLS[tool]]
    tools.append("Skill")
    return (
        "---\n"
        f"name: {agent['short']}\n"
        f"description: {quote(agent['description'])}\n"
        f"tools: {', '.join(tools)}\n"
        f"skills:\n  - {agent['skill']}\n"
        "---\n" + body(agent)
    )


def expected_files():
    """Map every generated path to its content."""
    files = {}
    for skill_dir in sorted(SKILLS.glob(f"{PREFIX}*")):
        if not skill_dir.is_dir() or skill_dir.name in PLAIN_SKILLS:
            continue
        agent = read_agent(skill_dir)
        copilot = ROOT / ".github" / "agents" / f"{agent['short']}.agent.md"
        claude = ROOT / ".claude" / "agents" / f"{agent['short']}.md"
        files[copilot] = copilot_file(agent)
        files[claude] = claude_file(agent)
    return files


def existing_files():
    """Every file in the two generated directories, bar the shared contracts."""
    copilot = ROOT / ".github" / "agents"
    found = {
        path
        for path in copilot.rglob("*")
        if path.is_file() and "_shared" not in path.relative_to(copilot).parts
    }
    found.update(p for p in (ROOT / ".claude" / "agents").rglob("*") if p.is_file())
    return found


def is_generated(path):
    return MARKER in path.read_text(encoding="utf-8", errors="replace")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="verify instead of writing"
    )
    args = parser.parse_args()
    try:
        expected = expected_files()
    except SpecError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    extra = sorted(existing_files() - set(expected))
    orphans = [path for path in extra if is_generated(path)]
    foreign = [
        f"not generated, remove or move it: {path.relative_to(ROOT)}"
        for path in extra
        if path not in orphans
    ]
    if args.check:
        problems = [f"orphan (no agent skill): {p.relative_to(ROOT)}" for p in orphans]
        problems.extend(foreign)
        for path, content in expected.items():
            if not path.is_file():
                problems.append(f"missing: {path.relative_to(ROOT)}")
            elif path.read_text(encoding="utf-8") != content:
                problems.append(f"stale: {path.relative_to(ROOT)}")
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            print(
                "Run `python3 .agents/tools/generate_agent_wrappers.py`.",
                file=sys.stderr,
            )
            return 1
        print(f"{len(expected)} agent files are up to date.")
        return 0
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    for path in orphans:
        path.unlink()
        print(f"removed orphan: {path.relative_to(ROOT)}")
    for problem in foreign:
        print(problem, file=sys.stderr)
    print(f"Wrote {len(expected)} agent files.")
    return 1 if foreign else 0


if __name__ == "__main__":
    sys.exit(main())
