#!/usr/bin/env python3
"""Build-time sizing check for Svc::TlmPacketizer

Reads the telemetry packet sets of a topology dictionary and writes a C++ source file that asserts, at compile time,
that every packet set fits MAX_PACKETIZER_MEMBERSHIPS and MAX_PACKETIZER_CHANNELS of TlmPacketizerCfg.hpp. It is
registered with register_fprime_dictionary_check and run by the dictionary_check build stage.

Exits 1 with a one-line message on stderr, writing no output, when the dictionary cannot be checked.
"""

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path

SCRIPT_NAME = "Svc/TlmPacketizer/tools/tlm_packetizer_sizing.py"
OMIT_LIST_VARIABLE = "FPRIME_TLM_PACKETIZER_OMIT_LIST"
DICTIONARY_SUFFIX = "TopologyDictionary.json"
CMAKE_TRUE = ("1", "ON", "YES", "TRUE", "Y")
CMAKE_FALSE = ("0", "OFF", "NO", "FALSE", "N", "")


class CheckError(Exception):
    """The dictionary cannot be checked"""


def identifier(name):
    """Convert a name to a C++ identifier"""
    converted = re.sub(r"[^A-Za-z0-9_]", "_", name)
    return converted if re.match(r"[A-Za-z_]", converted) else f"_{converted}"


def list_field(container, key, description):
    """Read a list field of a dictionary object; a missing or null field is an empty list"""
    value = container.get(key)
    if value is None:
        return []
    if not isinstance(value, list):
        raise CheckError(f"{description} is not a list")
    return value


def channel_names(container, key, description):
    """Read a list of channel names; a missing or null field is an empty list"""
    names = list_field(container, key, description)
    for name in names:
        if not isinstance(name, str):
            raise CheckError(f"{description} contains an entry that is not a string")
    return names


def measure_packet_set(packet_set):
    """Count the memberships, used channels and omitted channels of one packet set

    Returns:
        tuple of the set name, memberships, distinct channels listed in packets, omitted channels
    """
    if not isinstance(packet_set, dict):
        raise CheckError("telemetryPacketSets contains an entry that is not an object")
    name = packet_set.get("name")
    if not isinstance(name, str) or not name:
        raise CheckError("telemetryPacketSets contains a packet set without a name")
    memberships = 0
    used = set()
    for packet in list_field(packet_set, "members", f"members of packet set {name}"):
        if not isinstance(packet, dict):
            raise CheckError(f"members of packet set {name} contains an entry that is not an object")
        channels = channel_names(packet, "members", f"members of a packet of packet set {name}")
        memberships += len(channels)
        used.update(channels)
    omitted = set(channel_names(packet_set, "omitted", f"omitted of packet set {name}"))
    both = sorted(used & omitted)
    if both:
        raise CheckError(f"packet set {name} lists channel {both[0]} in a packet and as omitted")
    return name, memberships, len(used), len(omitted)


def measure_dictionary(dictionary):
    """Measure every packet set of a loaded dictionary"""
    if not isinstance(dictionary, dict):
        raise CheckError("dictionary is not a JSON object")
    measured = [
        measure_packet_set(packet_set)
        for packet_set in list_field(dictionary, "telemetryPacketSets", "telemetryPacketSets")
    ]
    names = [identifier(name) for name, _, _, _ in measured]
    for name in names:
        if names.count(name) > 1:
            raise CheckError(f"packet set name {name} is not unique")
    return measured


def render(measured, deployment, dictionary_name, count_omitted):
    """Render the C++ source asserting the sizes of the measured packet sets"""
    lines = [
        f"// Generated by {SCRIPT_NAME} from {dictionary_name}. Do not edit.",
        "// A failed assertion names the constant of TlmPacketizerCfg.hpp to raise and the value it needs.",
        '#include "TlmPacketizerConfig/TlmPacketizerCfg.hpp"',
        "",
    ]
    for name, memberships, used, omitted in measured:
        channels = used + omitted if count_omitted else used
        if count_omitted:
            detail = f"{used} listed in packets + {omitted} omitted; {OMIT_LIST_VARIABLE} is ON"
        else:
            detail = f"{used} listed in packets; {omitted} omitted not counted, {OMIT_LIST_VARIABLE} is OFF"
        lines += [
            f"namespace {identifier(deployment)} {{",
            "namespace TlmPacketizerSizing {",
            f"namespace {identifier(name)} {{",
            f"static constexpr FwSizeType MEMBERSHIPS = {memberships};",
            f"static constexpr FwSizeType CHANNELS = {channels};",
            "static_assert(Svc::MAX_PACKETIZER_MEMBERSHIPS >= MEMBERSHIPS,",
            f'              "Packet set {name} needs MAX_PACKETIZER_MEMBERSHIPS >= {memberships}");',
            "static_assert(Svc::MAX_PACKETIZER_CHANNELS >= CHANNELS,",
            f'              "Packet set {name} needs MAX_PACKETIZER_CHANNELS >= {channels} ({detail})");',
            f"}}  // namespace {identifier(name)}",
            "}  // namespace TlmPacketizerSizing",
            f"}}  // namespace {identifier(deployment)}",
            "",
        ]
    return "\n".join(lines)


def parse_definitions(definitions):
    """Read the -D arguments; returns whether omitted channels are counted (the default)"""
    count_omitted = True
    for definition in definitions:
        variable, separator, value = definition.partition("=")
        if not separator or variable != OMIT_LIST_VARIABLE:
            raise CheckError(f"unknown definition {definition}; expected {OMIT_LIST_VARIABLE}=ON|OFF")
        if value.upper() in CMAKE_TRUE:
            count_omitted = True
        elif value.upper() in CMAKE_FALSE:
            count_omitted = False
        else:
            raise CheckError(f"{OMIT_LIST_VARIABLE} must be ON or OFF, not {value}")
    return count_omitted


def check(dictionary_path, output_path, definitions):
    """Check one dictionary and write the generated source"""
    count_omitted = parse_definitions(definitions)
    try:
        with open(dictionary_path, "r", encoding="utf-8") as dictionary_file:
            dictionary = json.load(dictionary_file)
    except (OSError, UnicodeDecodeError) as error:
        raise CheckError(f"cannot read {dictionary_path}: {error}") from error
    except ValueError as error:
        raise CheckError(f"{dictionary_path} is not valid JSON: {error}") from error
    dictionary_name = Path(dictionary_path).name
    deployment = (
        dictionary_name[: -len(DICTIONARY_SUFFIX)]
        if dictionary_name.endswith(DICTIONARY_SUFFIX)
        else Path(dictionary_path).stem
    )
    text = render(measure_dictionary(dictionary), deployment, dictionary_name, count_omitted)
    # Written beside the output and renamed, so a failure leaves no partial output
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(
            "w", encoding="utf-8", dir=Path(output_path).resolve().parent, delete=False
        ) as temporary:
            temporary_path = temporary.name
            temporary.write(text)
        os.replace(temporary_path, output_path)
    except OSError as error:
        if temporary_path is not None and os.path.exists(temporary_path):
            os.remove(temporary_path)
        raise CheckError(f"cannot write {output_path}: {error}") from error


def main(arguments=None):
    """Command line entry point"""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("dictionary", help="topology dictionary JSON file")
    parser.add_argument("-o", "--output", required=True, help="C++ source file to write")
    parser.add_argument(
        "-D",
        dest="definitions",
        action="append",
        default=[],
        metavar="VARIABLE=VALUE",
        help=f"CMake variable; {OMIT_LIST_VARIABLE}=OFF leaves omitted channels out of the channel count",
    )
    parsed = parser.parse_args(arguments)
    try:
        check(parsed.dictionary, parsed.output, parsed.definitions)
    except CheckError as error:
        print(f"[ERROR] tlm_packetizer_sizing: {' '.join(str(error).split())}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
